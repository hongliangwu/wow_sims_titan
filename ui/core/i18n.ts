/** Localize preset / saved-set labels, falling back to common English word swaps. */
export function localizeLabel(en: string | undefined | null): string {
	if (!en) {
		return '';
	}
	if (!isZh()) {
		return en;
	}
	if (ZH[en]) {
		return ZH[en];
	}
	let out = en;
	for (const [re, cn] of PRESET_REPLACEMENTS) {
		out = out.replace(re, cn);
	}
	return out.replace(/\s+/g, ' ').trim();
}

export function localizeMap<K>(en: Map<K, string>): Map<K, string> {
	const out = new Map<K, string>();
	for (const [k, v] of en) {
		out.set(k, t(v));
	}
	return out;
}

export function localizeRecord<K extends string | number>(en: Record<K, string>): Record<K, string> {
	const out = {} as Record<K, string>;
	for (const key of Object.keys(en) as K[]) {
		out[key] = t(en[key]);
	}
	return out;
}
